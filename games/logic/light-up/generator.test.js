const test = require('node:test');
const assert = require('node:assert/strict');
const L = require('./logic.js');
const S = require('./solver.js');
const G = require('./generator.js');

test('createRng is deterministic and in [0, 1)', () => {
  const a = G.createRng(42);
  const b = G.createRng(42);
  const xs = Array.from({ length: 20 }, () => a());
  assert.deepEqual(xs, Array.from({ length: 20 }, () => b()));
  assert.ok(xs.every((x) => x >= 0 && x < 1));
  assert.notDeepEqual(xs, Array.from({ length: 20 }, G.createRng(43)));
});

test('randomInt stays in range', () => {
  const rng = G.createRng(1);
  const seen = new Set(Array.from({ length: 200 }, () => G.randomInt(rng, 5)));
  assert.deepEqual([...seen].sort(), [0, 1, 2, 3, 4]);
});

test('randomWalls are turned-around symmetric with about a fifth walls', () => {
  let total = 0;
  let walls = 0;
  for (let seed = 1; seed <= 40; seed++) {
    for (const size of [6, 7, 10]) {
      const w = G.randomWalls(size, G.createRng(seed));
      assert.equal(w.length, size * size);
      w.forEach((v, i) => assert.equal(v, w[size * size - 1 - i]));
      assert.ok(w.some((v) => !v));
      total += w.length;
      walls += w.filter(Boolean).length;
    }
  }
  const ratio = walls / total;
  assert.ok(ratio > 0.15 && ratio < 0.3, `wall ratio ${ratio}`);
});

test('randomLayout lights every white cell with no bulbs seeing each other', () => {
  for (let seed = 1; seed <= 30; seed++) {
    const rng = G.createRng(seed);
    const walls = G.randomWalls(7, rng);
    const bulbs = G.randomBulbs(7, walls, rng);
    const rows = G.numberedRows(7, walls, bulbs);
    const state = { size: 7, cells: walls.map((_, i) => (bulbs.has(i) ? 'bulb' : 'empty')) };
    assert.ok(L.isSolved(rows, state), rows.join('/'));
  }
});

test('numberedRows writes bulb counts on walls with open neighbors', () => {
  // wall at index 4 (center) has bulbs above and right
  const walls = [false, false, false, false, true, false, false, false, false];
  const bulbs = new Set([1, 5]);
  assert.deepEqual(G.numberedRows(3, walls, bulbs), ['...', '.2.', '...']);
  const boxed = [true, true, false, true, true, false, false, false, false];
  assert.deepEqual(G.numberedRows(3, boxed, new Set([2, 5, 6])), ['#1.', '11.', '...']);
});

test('grade sorts puzzles by the reasoning they need', () => {
  assert.equal(G.grade(['.3.', '...', '...']), 'easy');
  assert.equal(G.grade(['...', '.#.', '...']), 'hard');
});

test('generate makes a unique puzzle of the right size and level', () => {
  for (const level of ['easy', 'medium']) {
    const rows = G.generate(7, level, G.createRng(3));
    assert.equal(rows.length, 7);
    assert.ok(rows.every((r) => r.length === 7 && /^[.#0-4]+$/.test(r)));
    assert.equal(S.countSolutions(rows), 1);
    assert.equal(G.grade(rows), level);
  }
});

test('generate is deterministic for a seed', () => {
  assert.deepEqual(G.generate(7, 'easy', G.createRng(5)), G.generate(7, 'easy', G.createRng(5)));
});

test('generate gives up with an error when it cannot find a puzzle', () => {
  assert.throws(() => G.generate(7, 'easy', G.createRng(1), 0), /Could not generate/);
});

test('buildPuzzleSet builds graded, unique, distinct puzzles per level', () => {
  const set = G.buildPuzzleSet({ easy: 2, medium: 2, hard: 1 }, 1);
  assert.deepEqual(Object.keys(set), ['easy', 'medium', 'hard']);
  assert.deepEqual([set.easy.length, set.medium.length, set.hard.length], [2, 2, 1]);
  const sizes = { easy: 7, medium: 8, hard: 10 };
  const all = [];
  for (const level of Object.keys(set)) {
    for (const rows of set[level]) {
      assert.equal(rows.length, sizes[level]);
      assert.equal(S.countSolutions(rows), 1);
      assert.equal(G.grade(rows), level);
      all.push(rows.join('/'));
    }
  }
  assert.equal(new Set(all).size, 5);
  assert.deepEqual(G.buildPuzzleSet({ easy: 2, medium: 2, hard: 1 }, 1), set);
});

test('buildPuzzleSet throws when a level cannot be filled', () => {
  assert.throws(() => G.buildPuzzleSet({ easy: 1, medium: 0, hard: 0 }, 1, 0), /enough easy/);
});

test('puzzlesSource writes a loadable module', () => {
  const set = { easy: [['.3.', '...', '...']], medium: [], hard: [] };
  const text = G.puzzlesSource(set);
  assert.match(text, /Generated by make-puzzles\.js/);
  const mod = { exports: {} };
  new Function('module', 'root', text.replace(/\}\)\(this\);\s*$/, '})(root);'))(mod, {});
  assert.deepEqual(mod.exports, set);
});
