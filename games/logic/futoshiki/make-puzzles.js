// Builds the fixed puzzle list. Run `node make-puzzles.js` to rewrite puzzles.js.
// buildPuzzleList is exported so tests can exercise it with a tiny count.
const fs = require('fs');
const path = require('path');
const Gen = require('./generator.js');

const DEFAULT_COUNTS = { easy: 17, medium: 17, hard: 16 };
const SEED_BASE = { easy: 1000, medium: 2000, hard: 3000 };

function buildPuzzleList(counts = DEFAULT_COUNTS) {
  const list = [];
  for (const level of ['easy', 'medium', 'hard']) {
    for (let n = 1; n <= (counts[level] || 0); n++) {
      const p = Gen.generatePuzzle(SEED_BASE[level] + n, level);
      list.push({ id: level + '-' + n, difficulty: p.difficulty, size: p.size, givens: p.givens, h: p.h, v: p.v, solution: p.solution });
    }
  }
  return list;
}

function toSource(list) {
  const body = list.map((p) => '  ' + JSON.stringify(p)).join(',\n');
  return '// Generated by make-puzzles.js. Do not edit by hand.\n'
    + '(function (root) {\n'
    + '  const puzzles = [\n' + body + '\n  ];\n'
    + "  if (typeof module !== 'undefined' && module.exports) module.exports = puzzles;\n"
    + '  else root.FutoshikiPuzzles = puzzles;\n'
    + '})(this);\n';
}

module.exports = { buildPuzzleList, toSource, DEFAULT_COUNTS };

/* node:coverage ignore next 6 */
if (require.main === module) {
  const start = Date.now();
  const list = buildPuzzleList();
  fs.writeFileSync(path.join(__dirname, 'puzzles.js'), toSource(list));
  console.log('wrote ' + list.length + ' puzzles in ' + ((Date.now() - start) / 1000).toFixed(1) + 's');
}
