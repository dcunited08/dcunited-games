const test = require('node:test');
const assert = require('node:assert/strict');
const L = require('./logic.js');
const S = require('./solver.js');
const G = require('./generator.js');

const touching = (n, a, b) => Math.abs(Math.floor(a / n) - Math.floor(b / n)) + Math.abs((a % n) - (b % n)) === 1;

test('createRng is deterministic and in [0, 1)', () => {
  const a = G.createRng(42);
  const b = G.createRng(42);
  const xs = Array.from({ length: 20 }, () => a());
  assert.deepEqual(xs, Array.from({ length: 20 }, () => b()));
  assert.ok(xs.every((x) => x >= 0 && x < 1));
  assert.notDeepEqual(xs, Array.from({ length: 20 }, G.createRng(43)));
});

test('randomInt stays in range', () => {
  const rng = G.createRng(1);
  const seen = new Set(Array.from({ length: 200 }, () => G.randomInt(rng, 5)));
  assert.deepEqual([...seen].sort(), [0, 1, 2, 3, 4]);
});

// True when a piece runs alongside itself: two squares of it touch but are not
// next to each other along the piece. Such lines can be rerouted.
function touchesItself(n, piece) {
  return piece.some((a, i) => piece.some((b, j) => Math.abs(i - j) > 1 && touching(n, a, b)));
}

test('randomCover splits the board into lines of at least 3 squares that never touch themselves', () => {
  for (const size of [4, 5, 7, 9]) {
    for (let seed = 1; seed <= 8; seed++) {
      const pieces = G.randomCover(size, G.createRng(seed));
      assert.ok(pieces, `size ${size} seed ${seed}`);
      const all = pieces.flat();
      assert.equal(all.length, size * size);
      assert.equal(new Set(all).size, size * size);
      for (const piece of pieces) {
        assert.ok(piece.length >= 3);
        piece.forEach((c, i) => { if (i) assert.ok(touching(size, piece[i - 1], c)); });
        assert.equal(touchesItself(size, piece), false);
      }
    }
  }
});

test('randomCover is seeded and varies', () => {
  assert.deepEqual(G.randomCover(6, G.createRng(3)), G.randomCover(6, G.createRng(3)));
  assert.notDeepEqual(G.randomCover(6, G.createRng(3)), G.randomCover(6, G.createRng(4)));
});

test('randomCover returns null when the board cannot be cut into lines of 3', () => {
  assert.equal(G.randomCover(1, G.createRng(1)), null);
  assert.equal(G.randomCover(2, G.createRng(1)), null);
});

test('puzzleFromPieces numbers pairs in reading order and keeps the pieces as an answer', () => {
  const rows = G.puzzleFromPieces(3, [[0, 1, 2], [5, 4, 3], [6, 7, 8]]);
  assert.deepEqual(rows, ['1.1', '2.2', '3.3']);
  const p = L.parsePuzzle(rows);
  assert.deepEqual(p.ids, ['1', '2', '3']);
  const state = { size: 3, lines: { 1: [0, 1, 2], 2: [3, 4, 5], 3: [6, 7, 8] } };
  assert.equal(L.isSolved(p, state), true);
});

test('generate makes a puzzle with one answer in the pair range', () => {
  for (let seed = 1; seed <= 5; seed++) {
    const rows = G.generate(5, G.createRng(seed), { minPairs: 4, maxPairs: 5 });
    assert.ok(rows, 'found one');
    const p = L.parsePuzzle(rows);
    assert.equal(p.size, 5);
    assert.ok(p.ids.length >= 4 && p.ids.length <= 5);
    assert.equal(S.countSolutions(rows), 1);
    assert.deepEqual(rows, G.generate(5, G.createRng(seed), { minPairs: 4, maxPairs: 5 }));
  }
});

test('generate gives up (null) when nothing in the pair range turns up', () => {
  assert.equal(G.generate(5, G.createRng(1), { minPairs: 1, maxPairs: 1, restarts: 3 }), null);
});

test('generate gives up (null) when the solver runs out of budget', () => {
  assert.equal(G.generate(9, G.createRng(1), { minPairs: 1, maxPairs: 40, restarts: 2, budget: 1 }), null);
});

test('buildPuzzleSet fills each level with distinct puzzles of the right size', () => {
  const set = G.buildPuzzleSet({ easy: 3 }, 1);
  assert.equal(set.easy.length, 3);
  assert.equal(new Set(set.easy.map((r) => r.join('/'))).size, 3);
  assert.ok(set.easy.every((rows) => rows.length === 5));
  assert.deepEqual(set, G.buildPuzzleSet({ easy: 3 }, 1));
});

test('buildPuzzleSet throws when it cannot find enough puzzles', () => {
  assert.throws(() => G.buildPuzzleSet({ easy: 1 }, 1, { maxAttempts: 0 }), /Could not find/);
});

test('puzzlesSource writes a loadable puzzles.js', () => {
  const set = { easy: [['1.1', '2.2', '3.3']], medium: [], hard: [] };
  const src = G.puzzlesSource(set);
  assert.match(src, /^\/\/ Generated by make-puzzles\.js, do not edit by hand\./);
  const mod = { exports: {} };
  new Function('module', src).call({}, mod);
  assert.deepEqual(mod.exports, set);
});
