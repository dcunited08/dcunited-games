// Tents and Trees puzzle generator. No DOM. Used offline (make-puzzles.js) to
// make puzzles.js; also loadable in the browser (window.TentsGenerator) after
// logic.js and solver.js.
//
// Method: drop tents one at a time on random cells that touch no other tent,
// give each a tree on a free neighbouring cell, read the row and column
// numbers off the tents, and keep the board only if it has exactly one
// solution and the right difficulty.
(function (root) {
  const isNode = typeof require === 'function';
  const Logic = isNode ? require('./logic.js') : root.TentsLogic;
  const Solver = isNode ? require('./solver.js') : root.TentsSolver;

  // mulberry32: small seeded PRNG, returns floats in [0, 1).
  function createRng(seed) {
    let a = seed >>> 0;
    return function rng() {
      a = (a + 0x6D2B79F5) >>> 0;
      let t = a;
      t = Math.imul(t ^ (t >>> 15), t | 1);
      t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }

  const randomInt = (rng, n) => Math.floor(rng() * n);
  const ORTHO = [[-1, 0], [1, 0], [0, -1], [0, 1]];

  // A random board with `want` tents (fewer if it runs out of room). Returns
  // { puzzle: { grid, rows, cols }, tents: [cell indexes] }.
  function generate(size, want, rng) {
    const kind = Array(size * size).fill('.'); // '.', 'T' tree, 'A' tent
    const tents = [];
    const free = [];
    for (let i = 0; i < size * size; i++) free.push(i);
    for (let tries = 0; tents.length < want && tries < size * size * 20; tries++) {
      const i = free[randomInt(rng, free.length)];
      const r = Math.floor(i / size);
      const c = i % size;
      if (kind[i] !== '.') continue;
      let touching = false;
      for (let dr = -1; dr <= 1; dr++) {
        for (let dc = -1; dc <= 1; dc++) {
          const rr = r + dr;
          const cc = c + dc;
          if (rr >= 0 && cc >= 0 && rr < size && cc < size && kind[rr * size + cc] === 'A') touching = true;
        }
      }
      if (touching) continue;
      const spots = ORTHO.map(([dr, dc]) => [r + dr, c + dc])
        .filter(([rr, cc]) => rr >= 0 && cc >= 0 && rr < size && cc < size && kind[rr * size + cc] === '.')
        .map(([rr, cc]) => rr * size + cc);
      if (!spots.length) continue;
      kind[i] = 'A';
      kind[spots[randomInt(rng, spots.length)]] = 'T';
      tents.push(i);
    }
    const rows = Array(size).fill(0);
    const cols = Array(size).fill(0);
    for (const i of tents) { rows[Math.floor(i / size)]++; cols[i % size]++; }
    const grid = [];
    for (let r = 0; r < size; r++) {
      grid.push(kind.slice(r * size, (r + 1) * size).map((k) => (k === 'T' ? 'T' : '.')).join(''));
    }
    return { puzzle: { grid, rows, cols }, tents: tents.sort((a, b) => a - b) };
  }

  // size and tent count per level; `grade` is the difficulty a puzzle must have.
  const LEVELS = {
    easy: { size: 6, tents: 8, grade: 'easy' },
    medium: { size: 8, tents: 15, grade: 'medium' },
    hard: { size: 10, tents: 26, grade: 'hard' },
  };

  // True when the puzzle has the level's size, exactly one answer and the level's difficulty.
  function accepts(level, puzzle) {
    const spec = LEVELS[level];
    if (!spec || puzzle.grid.length !== spec.size) return false;
    return Solver.countSolutions(puzzle) === 1 && Solver.grade(puzzle) === spec.grade;
  }

  // { easy: [puzzle...], medium: [...], hard: [...] } with sizes 6, 8 and 10.
  // Deterministic for a given baseSeed. Puzzles are unique-answer, graded to
  // match their level, and never repeated.
  function buildPuzzleSet(counts, baseSeed = 1, options = {}) {
    const maxAttempts = options.maxAttempts === undefined ? 200000 : options.maxAttempts;
    const set = {};
    const seen = new Set();
    Object.keys(LEVELS).forEach((level, index) => {
      const spec = LEVELS[level];
      set[level] = [];
      for (let i = 0; set[level].length < (counts[level] || 0); i++) {
        if (i >= maxAttempts) throw new Error(`Could not build enough ${level} puzzles`);
        const rng = createRng(baseSeed * 1000003 + index * 100003 + i);
        const { puzzle } = generate(spec.size, spec.tents + randomInt(rng, 3) - 1, rng);
        const key = puzzle.grid.join('/') + puzzle.rows + puzzle.cols;
        if (seen.has(key) || !accepts(level, puzzle)) continue;
        seen.add(key);
        set[level].push(puzzle);
      }
    });
    return set;
  }

  // Text of puzzles.js for a set made by buildPuzzleSet.
  function puzzlesSource(set) {
    const lines = Object.keys(set).map((level) => {
      const rows = set[level].map((p) => `    ${JSON.stringify(p)},`).join('\n');
      return `  ${level}: [\n${rows}\n  ],`;
    });
    return `// Generated by make-puzzles.js, do not edit by hand.
// Tents and Trees starting puzzles: { grid (T = tree), rows, cols (tent counts) }.
// Browser global: window.TentsPuzzles.
(function (root) {
  const puzzles = {
${lines.join('\n')}
  };
  if (typeof module !== 'undefined' && module.exports) module.exports = puzzles;
  else root.TentsPuzzles = puzzles;
})(this);
`;
  }

  const api = { createRng, randomInt, generate, accepts, buildPuzzleSet, puzzlesSource, LEVELS };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.TentsGenerator = api;
})(this);
